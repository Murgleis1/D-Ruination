def stamp(name):
    m = np.zeros((16, 16), bool)
    yy, xx = np.mgrid[0:16, 0:16]; r = np.hypot(xx - 7.5, yy - 7.5)
    m |= (r > 6.7) & (r <= 7.7)
    g = [l for l in G[name].strip('\n').split('\n')]
    for y, l in enumerate(g):
        for x, c in enumerate(l):
            if c == '#': m[y + 2, x + 2] = True
    return m
PAPER, BOX = (226, 208, 166), (120, 88, 60)
RED = (150, 40, 32)
TYPE = {'Wraith': (96, 56, 128), 'Smelt': (196, 88, 32), 'Haywire': (176, 132, 16), 'Nonpareil': (110, 96, 84),
        'Firmament': (64, 112, 168), 'Verdant': (56, 120, 56), 'Gloaming': (48, 40, 88), 'Glamour': (196, 80, 128), 'Upheaval': (128, 84, 44)}
names = list(G)
FB = ImageFont.truetype('JacquardaBastarda9-Regular.ttf', 13)
Z = 6; cell = 22
sheet = Image.new('RGB', (9 * cell + 6, 2 * cell + 34), PAPER); d = ImageDraw.Draw(sheet); d.fontmode = '1'
for row, inkf in enumerate((lambda n: RED, lambda n: TYPE[n])):
    for i, n in enumerate(names):
        x0, y0 = 3 + i * cell, 16 + row * (cell + 2)
        d.rectangle([x0, y0, x0 + 19, y0 + 19], outline=BOX)
        m = stamp(n); ys, xs = np.nonzero(m)
        for y, x in zip(ys, xs): sheet.putpixel((x0 + 2 + x, y0 + 2 + y), inkf(n))
d.text((3, 1), 'single red ink  /  colour per Trial type', font=FB, fill=(66, 42, 28))
sheet.resize((sheet.width * Z, sheet.height * Z), Image.NEAREST).save('/tmp/stamps_sheet.png')
# labelled large reference
